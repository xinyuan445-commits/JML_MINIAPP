-- 报价工具 v2 - 报价记录快照表
-- 关键字段单独保存便于列表查询；form_snapshot保存当前表格全部内容。
CREATE TABLE `bj_quote_yx` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '内部主键',
  `quote_no` VARCHAR(40) NOT NULL COMMENT '报价单号',
  `customer` VARCHAR(100) NOT NULL COMMENT '客户',
  `category_code` VARCHAR(8) NOT NULL COMMENT '产品类别编码快照',
  `category_name` VARCHAR(100) NOT NULL COMMENT '产品类别名称快照',
  `unit` VARCHAR(8) DEFAULT NULL COMMENT '报价单位快照',
  `route_no` VARCHAR(20) DEFAULT NULL COMMENT '路线编号快照',
  `route_desc` VARCHAR(500) DEFAULT NULL COMMENT '完整工艺路线快照',
  `labor_cost` DECIMAL(16,4) NOT NULL DEFAULT 0 COMMENT '人工成本（含管理费用）',
  `aux_cost_excl_tax` DECIMAL(16,4) NOT NULL DEFAULT 0 COMMENT '辅助材料未税成本',
  `energy_cost` DECIMAL(16,4) NOT NULL DEFAULT 0 COMMENT '能耗成本（含公摊）',
  `material_cost_excl_tax` DECIMAL(16,4) NOT NULL DEFAULT 0 COMMENT '手工材料未税成本',
  `logistics_enabled` TINYINT NOT NULL DEFAULT 0 COMMENT '是否计入物流成本',
  `logistics_cost` DECIMAL(16,4) NOT NULL DEFAULT 0 COMMENT '物流单位成本',
  `base_cost_excl_tax` DECIMAL(16,4) NOT NULL DEFAULT 0 COMMENT '成本未税合计',
  `first_pass_rate` DECIMAL(8,4) DEFAULT NULL COMMENT '一次合格率百分数',
  `tax_rate` DECIMAL(8,4) DEFAULT NULL COMMENT '报价税率百分数',
  `cost_after_yield` DECIMAL(16,4) NOT NULL DEFAULT 0 COMMENT '合格率调整后成本',
  `direct_margin_rate` DECIMAL(8,4) DEFAULT NULL COMMENT '直营毛利率百分数',
  `direct_price_excl_tax` DECIMAL(16,4) DEFAULT NULL COMMENT '直营未税报价',
  `direct_price_incl_tax` DECIMAL(16,4) DEFAULT NULL COMMENT '直营含税报价',
  `dealer_margin_rate` DECIMAL(8,4) DEFAULT NULL COMMENT '经销商毛利率百分数',
  `dealer_price_excl_tax` DECIMAL(16,4) DEFAULT NULL COMMENT '经销商未税报价',
  `dealer_price_incl_tax` DECIMAL(16,4) DEFAULT NULL COMMENT '经销商含税报价',
  `form_snapshot` JSON NOT NULL COMMENT '当前报价表完整分组快照',
  `created_staff_id` VARCHAR(20) NOT NULL COMMENT '创建员工Id',
  `created_staff_name` VARCHAR(80) NOT NULL COMMENT '创建员工姓名快照',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_quote_no` (`quote_no`),
  KEY `idx_customer_time` (`customer`, `created_at`),
  KEY `idx_category_time` (`category_code`, `created_at`),
  KEY `idx_staff_time` (`created_staff_id`, `created_at`),
  KEY `idx_created_at` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='报价-报价记录完整快照';
