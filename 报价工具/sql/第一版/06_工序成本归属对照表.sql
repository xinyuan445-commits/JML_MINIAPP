-- ============================================================
-- 报价工具 - 工序成本归属对照表
-- 数据库: MySQL (utf8mb4)
-- 说明: 记录每道工序适用哪些成本类别（仅按工序归集的 A B C D E G）
--       F 管理成本按部门归集，不在此表，见 07_管理成本部门表
--       process_code 关联 bj_process_yx.code，cost_type 关联 bj_cost_type_yx.code
-- 表前缀 bj_ = 报价
-- ============================================================

CREATE TABLE IF NOT EXISTS `bj_process_cost_map_yx` (
  `id`           INT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '内部主键',
  `process_code` VARCHAR(8)   NOT NULL                COMMENT '工序编号，关联 bj_process_yx.code',
  `cost_type`    CHAR(1)      NOT NULL                COMMENT '成本类别，关联 bj_cost_type_yx.code（A B C D E G）',
  `created_at`   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_process_cost` (`process_code`, `cost_type`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='报价-工序成本归属对照表';

