-- ============================================================
-- 报价工具 - 工艺路线表（主表 + 工序明细）
-- 数据库: MySQL (utf8mb4)
-- 说明: 产品类别(+面数) -> 工艺路线 -> 有序工序步骤
--       step_name 保留流程图原始步骤名；process_code 为映射到的成本工序
--       is_optional 可选步骤(如覆膜)；is_pending 占位映射待处理（见 待处理.md）
--       入库打包仅流程不计成本，未纳入明细
-- 表前缀 bj_ = 报价
-- ============================================================

-- 工艺路线主表
CREATE TABLE IF NOT EXISTS `bj_route_yx` (
  `id`            INT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '内部主键',
  `code`          VARCHAR(8)   NOT NULL                COMMENT '路线编号',
  `category_code` VARCHAR(8)   NOT NULL                COMMENT '产品类别编号，关联 bj_product_category_yx.code',
  `side`          VARCHAR(10)  NOT NULL DEFAULT '单面' COMMENT '面数：单面/双面',
  `name`          VARCHAR(255) NOT NULL                COMMENT '路线名称/流程描述',
  `is_enabled`    TINYINT      NOT NULL DEFAULT 1      COMMENT '是否启用：1启用 0停用',
  `is_default`    TINYINT      NOT NULL DEFAULT 0      COMMENT '同一产品类别下是否默认路线：1是 0否',
  `remark`        VARCHAR(255)          DEFAULT NULL   COMMENT '备注',
  `created_at`    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP                       COMMENT '创建时间',
  `updated_at`    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_code` (`code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='报价-工艺路线主表';

-- 工艺路线工序明细
CREATE TABLE IF NOT EXISTS `bj_route_step_yx` (
  `id`           INT UNSIGNED  NOT NULL AUTO_INCREMENT COMMENT '内部主键',
  `route_code`   VARCHAR(8)    NOT NULL                COMMENT '路线编号，关联 bj_route_yx.code',
  `step_no`      INT           NOT NULL                COMMENT '步序',
  `step_name`    VARCHAR(50)   NOT NULL                COMMENT '流程图原始步骤名',
  `process_code` VARCHAR(8)             DEFAULT NULL   COMMENT '映射工序编号，关联 bj_process_yx.code',
  `is_optional`  TINYINT       NOT NULL DEFAULT 0      COMMENT '是否可选步骤：1可选 0必经',
  `is_pending`   TINYINT       NOT NULL DEFAULT 0      COMMENT '是否占位待处理映射：1是 0否',
  `coefficient`  DECIMAL(8,4)  NOT NULL DEFAULT 1      COMMENT '成本系数，默认1',
  `remark`       VARCHAR(255)           DEFAULT NULL   COMMENT '备注',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_route_step` (`route_code`, `step_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='报价-工艺路线工序明细表';

