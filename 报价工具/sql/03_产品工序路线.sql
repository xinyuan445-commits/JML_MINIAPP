-- 核对每个产品的成本工序路线。
SELECT
  pc.code AS product_code,
  pc.name AS product_name,
  pp.seq_no,
  COALESCE(p.process_code, pp.process_group) AS process_code_or_group,
  COALESCE(p.process_name, CONCAT('工序组：', pp.process_group)) AS process_name,
  pp.remark
FROM bj_product_cost_yx pc
LEFT JOIN bj_product_process_yx pp ON pp.product_code=pc.code
LEFT JOIN bj_process_yx p ON p.process_code=pp.process_code
ORDER BY pc.code, pp.seq_no;
