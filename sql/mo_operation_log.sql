CREATE TABLE IF NOT EXISTS mo_operation_log_yx (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    event_key VARCHAR(160) NULL UNIQUE,
    event_type VARCHAR(40) NOT NULL,
    event_name VARCHAR(80) NOT NULL,
    occurred_at DATETIME NOT NULL,
    operator_id VARCHAR(100) NULL,
    operator_name VARCHAR(100) NOT NULL DEFAULT '',
    worker_names VARCHAR(1000) NOT NULL DEFAULT '',
    worker_details JSON NULL,
    mo_code VARCHAR(100) NOT NULL,
    sort_seq INT NOT NULL,
    route_id BIGINT NULL,
    seq INT NULL,
    process_name VARCHAR(100) NOT NULL DEFAULT '',
    station_id BIGINT NULL,
    station_name VARCHAR(100) NOT NULL DEFAULT '',
    qty DECIMAL(18,4) NULL,
    qty_a DECIMAL(18,4) NULL,
    qty_a1 DECIMAL(18,4) NULL,
    qty_a2 DECIMAL(18,4) NULL,
    qty_c DECIMAL(18,4) NULL,
    reason VARCHAR(1000) NULL,
    photo_urls JSON NULL,
    source_type VARCHAR(40) NULL,
    source_id BIGINT NULL,
    details JSON NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_operation_log_time (occurred_at, id),
    INDEX idx_operation_log_operator (operator_name, occurred_at),
    INDEX idx_operation_log_workorder (mo_code, sort_seq, occurred_at),
    INDEX idx_operation_log_event (event_type, occurred_at),
    INDEX idx_operation_log_process (process_name, station_name, occurred_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
